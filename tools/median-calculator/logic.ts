// ── Median Calculator Logic ──

export interface ParsedDataset {
  values: number[];
  invalidTokens: string[];
}

const SPLIT_RE = /[\s,;\t\n]+/;

export function parseDataset(input: string): ParsedDataset {
  const tokens = input.split(SPLIT_RE).map((t) => t.trim()).filter(Boolean);
  const values: number[] = [];
  const invalidTokens: string[] = [];
  for (const token of tokens) {
    const n = Number(token);
    if (token !== "" && !isNaN(n) && isFinite(n)) values.push(n);
    else invalidTokens.push(token);
  }
  return { values, invalidTokens };
}

export interface MedianResult {
  median: number;
  sorted: number[];
  count: number;
  isEven: boolean;
  min: number;
  max: number;
  sum: number;
  mean: number;
  middlePosition: string;
  formula: string;
  calculation: string;
}

export function calculateMedian(values: number[], decimals: number): MedianResult | null {
  if (values.length === 0) return null;

  const sorted = [...values].sort((a, b) => a - b);
  const n = sorted.length;
  const isEven = n % 2 === 0;
  const round = (v: number) => parseFloat(v.toFixed(decimals));

  let median: number;
  let middlePosition: string;
  let formula: string;
  let calculation: string;

  if (isEven) {
    const lo = sorted[n / 2 - 1];
    const hi = sorted[n / 2];
    median = round((lo + hi) / 2);
    middlePosition = `Positions ${n / 2} & ${n / 2 + 1}`;
    formula = "Median = (Middle 1 + Middle 2) / 2";
    calculation = `(${lo} + ${hi}) / 2 = ${median}`;
  } else {
    const mid = Math.floor(n / 2);
    median = round(sorted[mid]);
    middlePosition = `Position ${mid + 1}`;
    formula = "Median = Middle Value";
    calculation = `Middle value = ${median}`;
  }

  const sum = sorted.reduce((a, b) => a + b, 0);

  return {
    median, sorted, count: n, isEven,
    min: sorted[0], max: sorted[n - 1], sum,
    mean: round(sum / n),
    middlePosition, formula, calculation,
  };
}

