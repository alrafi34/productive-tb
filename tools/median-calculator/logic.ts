export function buildTextReport(result: MedianResult, originalInput: string): string {
  const ts = new Date().toLocaleString("en-US");
  return [
    "Median Calculator Report",
    "=========================",
    `Generated: ${ts}`,
    "",
    `Original Dataset: ${originalInput.trim()}`,
    `Sorted Dataset: ${result.sorted.join(", ")}`,
    "",
    `Total Count: ${result.count} (${result.isEven ? "Even" : "Odd"})`,
    `Minimum: ${result.min}`,
    `Maximum: ${result.max}`,
    `Sum: ${result.sum}`,
    `Mean: ${result.mean}`,
    "",
    `Median: ${result.median}`,
    `Formula: ${result.formula}`,
    `Calculation: ${result.calculation}`,
    `Middle Position: ${result.middlePosition}`,
    "",
    "Generated by Median Calculator — https://productivetoolbox.com",
  ].join("\n");
}

export function buildCSVReport(result: MedianResult): string {
  const rows = [
    ["Metric", "Value"],
    ["Count", String(result.count)],
    ["Minimum", String(result.min)],
    ["Maximum", String(result.max)],
    ["Sum", String(result.sum)],
    ["Mean", String(result.mean)],
    ["Median", String(result.median)],
    ["Sorted Dataset", result.sorted.join(" ")],
  ];
  return rows.map((r) => r.map((c) => `"${c}"`).join(",")).join("\n");
}
